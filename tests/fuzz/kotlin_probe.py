os.makedirs(HERE + '/ko', exist_ok=True)
only = sys.argv[1:]
ok, rej, bad = 0, [], []
for name, src in cases.items():
    if only and name not in only:
        continue
    path = HERE + '/ko/' + name + '.mam'
    open(path, 'w', encoding='utf-8').write(src)
    out = HERE + '/ko/o'
    shutil.rmtree(out, ignore_errors=True)
    p = subprocess.run([COMPILER, path, out], capture_output=True, timeout=60, input=b'')
    if p.returncode != 0:
        lines = p.stderr.decode('utf-8', 'replace').strip().splitlines()
        msg = lines[0].split(': ', 1)[-1] if lines else f'exit {p.returncode}'
        rej.append(f'{name}: {msg[:70]}')
        continue
    r = subprocess.run(['java', '-Xverify:all', '-cp', out, 'Main'], capture_output=True, timeout=30, input=b'')
    if r.returncode != 0:
        bad.append(f'{name}: ' + r.stderr.decode('utf-8', 'replace').strip().splitlines()[0][:120])
    else:
        ok += 1
print('ok', ok, 'rejected', len(rej), 'runtime', len(bad))
print('--- rejected'); print('\n'.join(rej))
print('--- runtime'); print('\n'.join(bad))
